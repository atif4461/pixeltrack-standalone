/**
 * Brief description of the function kernel_countMultiplicity
 *
 * Detailed description of the function kernel_countMultiplicity
 * This function takes three parameters: foundNtuplets, quality, and tupleMultiplicity
 * It iterates over the foundNtuplets and checks their size and quality
 * If the size is less than 3 or the quality is duplicate, it skips to the next iteration
 * Otherwise, it asserts that the quality is bad and counts the direct multiplicity
 * If the number of hits is greater than 5, it prints an error message
 * Finally, it asserts that the number of hits is less than 8
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.2.
*/ 
void kernel_countMultiplicity(HitContainer const *__restrict__ foundNtuplets,
                              Quality const *__restrict__ quality,
                              CAConstants::TupleMultiplicity *tupleMultiplicity) {
  auto first = 0;
  for (int it = first, nt = foundNtuplets->nbins(); it < nt; it++) {
    auto nhits = foundNtuplets->size(it);
    if (nhits < 3)
      continue;
    if (quality[it] == trackQuality::dup)
      continue;
    assert(quality[it] == trackQuality::bad);
    if (nhits > 5)
      printf("wrong mult %d %d\n", it, nhits);
    assert(nhits < 8);
    tupleMultiplicity->countDirect(nhits);
  }
}

