/**
 * @brief Fills hit detector indices container with data from tracking rec hits and hit container.
 *
 * This function copies offsets from the input hit container and fills hit indices
 * based on the tracking rec hits data.
 *
 * @param[in] tuples Input hit container with bin information.
 * @param[in] hhp View of tracking rec hits data.
 * @param[out] hitDetIndices Output container to store hit detector indices.
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.2.
*/ 
void kernel_fillHitDetIndices(HitContainer const *__restrict__ tuples,
                              TrackingRecHit2DSOAView const *__restrict__ hhp,
                              HitContainer *__restrict__ hitDetIndices) {
  int first = 0;
  // copy offsets
  for (int idx = first, ntot = tuples->totbins(); idx < ntot; idx++) {
    hitDetIndices->off[idx] = tuples->off[idx];
  }
  // fill hit indices
  auto const &hh = *hhp;
  auto nhits = hh.nHits();
  for (int idx = first, ntot = tuples->size(); idx < ntot; idx++) {
    assert(tuples->bins[idx] < nhits);
    hitDetIndices->bins[idx] = hh.detectorIndex(tuples->bins[idx]);
  }
}

/**
 * Performs statistical analysis for hits in tracks.
 *
 * @param hitToTuple HitToTuple object containing data for processing
 * @param counters Counters object to store results
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.2.
*/ 
void kernel_doStatsForHitInTracks(CAHitNtupletGeneratorKernelsCPU::HitToTuple const *__restrict__ hitToTuple,
                                  CAHitNtupletGeneratorKernelsCPU::Counters *counters) {
  auto &c = *counters;
  int first = 0;
  for (int idx = first, ntot = hitToTuple->nbins(); idx < ntot; idx++) {
    if (hitToTuple->size(idx) == 0)
      continue;  // SHALL NOT BE break
    atomicAdd(&c.nUsedHits, 1);
    if (hitToTuple->size(idx) > 1)
      atomicAdd(&c.nDupHits, 1);
  }
}

/**
 * @brief Kernel function for cleaning triplets
 *
 * This function cleans triplets by removing duplicate tracks and selecting the best tip.
 *
 * @param hhp TrackingRecHit2DSOAView object containing hit data
 * @param ptuples HitContainer object containing tuple data
 * @param ptracks TkSoA object containing track data
 * @param quality array of quality values for each hit
 * @param phitToTuple CAHitNtupletGeneratorKernelsCPU object containing hit-to-tuple mapping
  
 * @class TrackingRecHit2DSOAView
 * @brief View class for tracking rec hits in 2D SOA format
 
 * @class HitContainer
 * @brief Container class for storing hit data
 
 * @class TkSoA
 * @brief Class representing track data in SOA format
 
 * @class CAHitNtupletGeneratorKernelsCPU
 * @brief Class generating hit-to-tuple mappings for CPU kernels
 
 * @enum trackQuality
 * @brief Enumerated type for track qualities
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.2.
*/ 
void kernel_tripletCleaner(TrackingRecHit2DSOAView const *__restrict__ hhp,
                           HitContainer const *__restrict__ ptuples,
                           TkSoA const *__restrict__ ptracks,
                           Quality *__restrict__ quality,
                           CAHitNtupletGeneratorKernelsCPU::HitToTuple const *__restrict__ phitToTuple) {
  constexpr auto bad = trackQuality::bad;
  constexpr auto dup = trackQuality::dup;
  // constexpr auto loose = trackQuality::loose;

  auto &hitToTuple = *phitToTuple;
  auto const &foundNtuplets = *ptuples;
  auto const &tracks = *ptracks;

  //  auto const & hh = *hhp;
  // auto l1end = hh.hitsLayerStart_d[1];

  int first = 0;
  for (int idx = first, ntot = hitToTuple.nbins(); idx < ntot; idx++) {
    if (hitToTuple.size(idx) < 2)
      continue;

    float mc = 10000.f;
    uint16_t im = 60000;
    uint32_t maxNh = 0;

    // find maxNh
    for (auto it = hitToTuple.begin(idx); it != hitToTuple.end(idx); ++it) {
      uint32_t nh = foundNtuplets.size(*it);
      maxNh = std::max(nh, maxNh);
    }
    // kill all tracks shorter than maxHn (only triplets???)
    for (auto it = hitToTuple.begin(idx); it != hitToTuple.end(idx); ++it) {
      uint32_t nh = foundNtuplets.size(*it);
      if (maxNh != nh)
        quality[*it] = dup;
    }

    if (maxNh > 3)
      continue;
    // if (idx>=l1end) continue;  // only for layer 1
    // for triplets choose best tip!
    for (auto ip = hitToTuple.begin(idx); ip != hitToTuple.end(idx); ++ip) {
      auto const it = *ip;
      if (quality[it] != bad && std::abs(tracks.tip(it)) < mc) {
        mc = std::abs(tracks.tip(it));
        im = it;
      }
    }
    // mark duplicates
    for (auto ip = hitToTuple.begin(idx); ip != hitToTuple.end(idx); ++ip) {
      auto const it = *ip;
      if (quality[it] != bad && it != im)
        quality[it] = dup;  //no race:  simple assignment of the same constant
    }
  }  // loop over hits
}

/**
 * Brief description of the function kernel_print_found_ntuplets
 *
 * Detailed description of the function kernel_print_found_ntuplets
 * This function prints the found n-tuplets for a given event
 * It takes several parameters including the tracking rec hit, 
 * hit container, tracks, quality, hit to tuple generator and more
 * It iterates over the found n-tuplets and prints their details
 *
 * @param hhp TrackingRecHit2DSOAView object
 * @param ptuples HitContainer object
 * @param ptracks TkSoA object
 * @param quality Quality object
 * @param phitToTuple CAHitNtupletGeneratorKernelsCPUHitToTuple object
 * @param maxPrint maximum number of n-tuplets to print
 * @param iev event number
 * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.2.
*/ 
void kernel_print_found_ntuplets(TrackingRecHit2DSOAView const *__restrict__ hhp,
                                 HitContainer const *__restrict__ ptuples,
                                 TkSoA const *__restrict__ ptracks,
                                 Quality const *__restrict__ quality,
                                 CAHitNtupletGeneratorKernelsCPU::HitToTuple const *__restrict__ phitToTuple,
                                 uint32_t maxPrint,
                                 int iev) {
  auto const &foundNtuplets = *ptuples;
  auto const &tracks = *ptracks;
  int first = 0;
  for (int i = first, np = std::min(maxPrint, foundNtuplets.nbins()); i < np; i += 1) {
    auto nh = foundNtuplets.size(i);
    if (nh < 3)
      continue;
    printf("TK: %d %d %d %f %f %f %f %f %f %f %d %d %d %d %d\n",
           10000 * iev + i,
           int(quality[i]),
           nh,
           tracks.charge(i),
           tracks.pt(i),
           tracks.eta(i),
           tracks.phi(i),
           tracks.tip(i),
           tracks.zip(i),
           //           asinhf(fit_results[i].par(3)),
           tracks.chi2(i),
           *foundNtuplets.begin(i),
           *(foundNtuplets.begin(i) + 1),
           *(foundNtuplets.begin(i) + 2),
           nh > 3 ? int(*(foundNtuplets.begin(i) + 3)) : -1,
           nh > 4 ? int(*(foundNtuplets.begin(i) + 4)) : -1);
  }
}

