namespace edm {
/**
 * @brief Class representing a source of events for processing.
 *
 * This class provides an interface for producing events and managing their processing.
 * It includes functionality for starting event processing, retrieving the maximum number of events,
 * and checking the number of processed events.
 
class Source {
     * @brief Constructor for the Source class.
   *
   * Initializes the source with parameters such as the maximum number of events, runtime in minutes,
   * product registry, data directory, and validation flag.
   *
   * @param maxEvents Maximum number of events to process.
   * @param runForMinutes Runtime in minutes.
   * @param reg Product registry reference.
   * @param datadir Path to the data directory.
   * @param validation Flag indicating whether validation is enabled.
   
     * @brief Starts the event processing.
   
     * @brief Retrieves the maximum number of events.
   *
   * @return Maximum number of events.
   
     * @brief Retrieves the number of processed events.
   *
   * @return Number of processed events.
   
     * @brief Produces an event for the specified stream ID and product registry.
   *
   * This method is thread-safe.
   *
   * @param streamId Stream ID for the event.
   * @param reg Product registry reference.
   * @return Unique pointer to the produced event.
   * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.01.
*/ 
  class Source {
  public:
    explicit Source(
        int maxEvents, int runForMinutes, ProductRegistry& reg, std::filesystem::path const& datadir, bool validation);

    void startProcessing();

    int maxEvents() const { return maxEvents_; }
    int processedEvents() const { return numEvents_; }

    // thread safe
    std::unique_ptr<Event> produce(int streamId, ProductRegistry const& reg);

  private:
    int maxEvents_;

    // these are all for the mode where the processing length is limited by time
    int const runForMinutes_;
    std::chrono::steady_clock::time_point startTime_;
    std::mutex timeMutex_;
    std::atomic<int> numEventsTimeLastCheck_ = 0;
    std::atomic<bool> shouldStop_ = false;

    std::atomic<int> numEvents_ = 0;
    EDPutTokenT<FEDRawDataCollection> const rawToken_;
    EDPutTokenT<DigiClusterCount> digiClusterToken_;
    EDPutTokenT<TrackCount> trackToken_;
    EDPutTokenT<VertexCount> vertexToken_;
    std::vector<FEDRawDataCollection> raw_;
    std::vector<DigiClusterCount> digiclusters_;
    std::vector<TrackCount> tracks_;
    std::vector<VertexCount> vertices_;
    bool const validation_;
  };
}  // namespace edm

#endif
