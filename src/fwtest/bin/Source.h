#ifndef Source_h
#define Source_h

#include <atomic>
#include <chrono>
#include <filesystem>
#include <memory>
#include <mutex>
#include <string>

#include "Framework/Event.h"
#include "DataFormats/FEDRawDataCollection.h"
#include "DataFormats/DigiClusterCount.h"
#include "DataFormats/TrackCount.h"
#include "DataFormats/VertexCount.h"

namespace edm {
/**
 * @brief Class representing a source of events in a data processing pipeline.
 *
 * This class provides an interface for generating and producing events,
 * as well as managing the event production process.
 
class Source {
     * @brief Constructs a new Source object with the specified parameters.
   *
   * @param maxEvents Maximum number of events to process.
   * @param runForMinutes Number of minutes to run the processing for.
   * @param reg Reference to the product registry.
   * @param datadir Path to the data directory.
   * @param validation Flag indicating whether validation is enabled.
   
     * @brief Reconfigures the source with new parameters.
   *
   * @param maxEvents New maximum number of events to process.
   * @param runForMinutes New number of minutes to run the processing for.
   
     * @brief Starts the event processing.
   
     * @brief Returns the maximum number of events to process.
   *
   * @return Maximum number of events.
   
     * @brief Returns the number of events that have been processed.
   *
   * @return Number of processed events.
   
     * @brief Produces an event for the specified stream ID and product registry.
   *
   * This method is thread-safe.
   *
   * @param streamId Stream ID for which to produce the event.
   * @param reg Reference to the product registry.
   * @return Unique pointer to the produced event.
   * This comment was generated by meta-llama/Llama-3.3-70B-Instruct:None at temperature 0.5.
*/ 
  class Source {
  public:
    explicit Source(
        int maxEvents, int runForMinutes, ProductRegistry& reg, std::filesystem::path const& datadir, bool validation);

    void reconfigure(int maxEvents, int runForMinutes);
    void startProcessing();

    int maxEvents() const { return maxEvents_; }
    int processedEvents() const { return numEvents_; }

    // thread safe
    std::unique_ptr<Event> produce(int streamId, ProductRegistry const& reg);

  private:
    int maxEvents_;

    // these are all for the mode where the processing length is limited by time
    int runForMinutes_;
    std::chrono::steady_clock::time_point startTime_;
    std::mutex timeMutex_;
    std::atomic<int> numEventsTimeLastCheck_ = 0;
    std::atomic<bool> shouldStop_ = false;

    std::atomic<int> numEvents_ = 0;
    EDPutTokenT<FEDRawDataCollection> const rawToken_;
    EDPutTokenT<DigiClusterCount> digiClusterToken_;
    EDPutTokenT<TrackCount> trackToken_;
    EDPutTokenT<VertexCount> vertexToken_;
    std::vector<FEDRawDataCollection> raw_;
    std::vector<DigiClusterCount> digiclusters_;
    std::vector<TrackCount> tracks_;
    std::vector<VertexCount> vertices_;
    bool const validation_;
  };
}  // namespace edm

#endif
